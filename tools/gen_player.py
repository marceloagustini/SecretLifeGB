
def to_gb_tile(pixels):
    # pixels is a list of 8 strings, each 8 chars long (0-3)
    hex_bytes = []
    for row in pixels:
        lo = 0
        hi = 0
        for i, char in enumerate(row):
            val = int(char)
            bit = 7 - i
            if val & 1:
                lo |= (1 << bit)
            if val & 2:
                hi |= (1 << bit)
        hex_bytes.append(f"0x{lo:02X}")
        hex_bytes.append(f"0x{hi:02X}")
    return hex_bytes

def convert_16x16(name, frames):
    print(f"const unsigned char {name}[] = {{")
    
    for frame_name, pixels in frames.items():
        print(f"    // {frame_name}")
        # Standardize input
        rows = [r.strip().replace(' ', '') for r in pixels if r.strip()]
        if len(rows) != 16:
            print(f"Error: Frame {frame_name} has {len(rows)} rows, expected 16")
            continue
            
        # Split into 4 tiles (TL, TR, BL, BR)
        # TL: rows 0-7, cols 0-7
        tl = [r[0:8] for r in rows[0:8]]
        # TR: rows 0-7, cols 8-15
        tr = [r[8:16] for r in rows[0:8]]
        # BL: rows 8-15, cols 0-7
        bl = [r[0:8] for r in rows[8:16]]
        # BR: rows 8-15, cols 8-15
        br = [r[8:16] for r in rows[8:16]]
        
        for i, tile in enumerate([tl, tr, bl, br]):
             bytes_str = ", ".join(to_gb_tile(tile))
             print(f"    {bytes_str}, // Tile {i}")
             
    print("};")

