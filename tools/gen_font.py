def create_font_tile(pattern):
    """Convert 8x8 pattern to GameBoy tile data"""
    tile_data = []
    for row in pattern:
        byte1 = 0
        byte2 = 0
        for i, pixel in enumerate(row):
            bit_pos = 7 - i
            if pixel == '1':
                byte1 |= (1 << bit_pos)
            elif pixel == '2':
                byte2 |= (1 << bit_pos)
            elif pixel == '3':
                byte1 |= (1 << bit_pos)
                byte2 |= (1 << bit_pos)
        tile_data.append(byte1)
        tile_data.append(byte2)
    return tile_data

