COLORS_BGR = [(255, 255, 255), (192, 192, 192), (96, 96, 96), (0, 0, 0)]

def generate_png():
    all_tiles = {**tiles_design, **anim_design}
    tile_size = 8
    grid_width = 16
    max_idx = 76 # Force to match expected range
    grid_height = (max_idx // grid_width) + 1
    img_w = grid_width * tile_size
    img_h = grid_height * tile_size
    
    pixels = [[(255, 0, 255) for _ in range(img_w)] for _ in range(img_h)]
    
    for idx, rows in all_tiles.items():
        bx, by = (idx % grid_width) * 8, (idx // grid_width) * 8
        for y, row in enumerate(rows):
            for x, char in enumerate(row):
                pixels[by + y][bx + x] = COLORS_BGR[int(char)]
    
    img = Image.new('RGB', (img_w, img_h))
    for y in range(img_h):
        for x in range(img_w):
            img.putpixel((x, y), pixels[y][x])
    
    output_path = "res/tileset.png"
    img.save(output_path)
    print(f"Exported to {output_path}")

if __name__ == "__main__":
    generate_png()
