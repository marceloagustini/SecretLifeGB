
def get_char_hex(char_code):
    # Improved 8x8 font bitmap with better spacing
    # 0 = Background (white), 1 = Foreground (black)
    
    font = {
        ' ': [0x00]*8,
        'A': [0x00, 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x00],
        'B': [0x00, 0x7C, 0x66, 0x7C, 0x66, 0x66, 0x7C, 0x00],
        'C': [0x00, 0x3C, 0x66, 0x60, 0x60, 0x66, 0x3C, 0x00],
        'D': [0x00, 0x78, 0x6C, 0x66, 0x66, 0x6C, 0x78, 0x00],
        'E': [0x00, 0x7E, 0x60, 0x7C, 0x60, 0x60, 0x7E, 0x00],
        'F': [0x00, 0x7E, 0x60, 0x7C, 0x60, 0x60, 0x60, 0x00],
        'G': [0x00, 0x3C, 0x60, 0x60, 0x6E, 0x66, 0x3C, 0x00],
        'H': [0x00, 0x66, 0x66, 0x7E, 0x7E, 0x66, 0x66, 0x00],
        'I': [0x00, 0x3C, 0x18, 0x18, 0x18, 0x18, 0x3C, 0x00],
        'J': [0x00, 0x1E, 0x0C, 0x0C, 0x0C, 0x6C, 0x38, 0x00],
        'K': [0x00, 0x66, 0x6C, 0x78, 0x78, 0x6C, 0x66, 0x00],
        'L': [0x00, 0x60, 0x60, 0x60, 0x60, 0x60, 0x7E, 0x00],
        'M': [0x00, 0x63, 0x77, 0x7F, 0x6B, 0x63, 0x63, 0x00],
        'N': [0x00, 0x66, 0x76, 0x7E, 0x6E, 0x66, 0x66, 0x00],
        'O': [0x00, 0x3C, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x00],
        'P': [0x00, 0x7C, 0x66, 0x66, 0x7C, 0x60, 0x60, 0x00],
        'Q': [0x00, 0x3C, 0x66, 0x66, 0x6A, 0x6C, 0x36, 0x00],
        'R': [0x00, 0x7C, 0x66, 0x66, 0x7C, 0x6C, 0x66, 0x00],
        'S': [0x00, 0x3C, 0x60, 0x3C, 0x06, 0x06, 0x3C, 0x00],
        'T': [0x00, 0x7E, 0x18, 0x18, 0x18, 0x18, 0x18, 0x00],
        'U': [0x00, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x00],
        'V': [0x00, 0x66, 0x66, 0x66, 0x66, 0x3C, 0x18, 0x00],
        'W': [0x00, 0x63, 0x63, 0x6B, 0x7F, 0x77, 0x63, 0x00],
        'X': [0x00, 0x66, 0x3C, 0x18, 0x18, 0x3C, 0x66, 0x00],
        'Y': [0x00, 0x66, 0x66, 0x3C, 0x18, 0x18, 0x18, 0x00],
        'Z': [0x00, 0x7E, 0x0C, 0x18, 0x30, 0x60, 0x7E, 0x00],
        ',': [0x00, 0x00, 0x00, 0x00, 0x00, 0x18, 0x18, 0x30],
        '?': [0x00, 0x3C, 0x66, 0x0C, 0x18, 0x00, 0x18, 0x00],
        # Box drawing characters
        '┌': [0xFF, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80],
        '─': [0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        '┐': [0xFF, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01],
        '│': [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80],
        '└': [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0xFF],
        '┘': [0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0xFF],
    }
    
    bitmap = font.get(char_code, [0x00]*8)
    
    # Convert to 2bpp (color 3 = black for text)
    hex_data = []
    for row in bitmap:
        # Plane 0 and plane 1 both set = color 3 (darkest)
        hex_data.append(row)
        hex_data.append(row)
        
    return hex_data

chars = " ABCDEFGHIJKLMNOPQRSTUVWXYZ,?┌─┐│└┘"
print("const unsigned char font_data[] = {")
for c in chars:
    data = get_char_hex(c)
    print(f"    // {repr(c)}")
    print("    " + ", ".join([f"0x{b:02X}" for b in data]) + ",")
print("};")
